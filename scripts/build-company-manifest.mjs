import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const companyDirectory = path.join(root, "data", "companies");
const outputFile = path.join(root, "lib", "generated-company-manifest.ts");

const companies = fs
  .readdirSync(companyDirectory)
  .filter((file) => file.endsWith(".json"))
  .sort()
  .flatMap((file) => {
    const graph = JSON.parse(fs.readFileSync(path.join(companyDirectory, file), "utf8"));
    if (graph.verified !== true) return [];
    return [{ id: path.basename(file, ".json"), file }];
  });

const identifierFor = (index) => `company${index + 1}`;
const imports = companies.map(({ file }, index) => `import ${identifierFor(index)} from "@/data/companies/${file}";`);
const entries = companies.map(({ id }, index) => `  { id: ${JSON.stringify(id)}, data: ${identifierFor(index)} },`);

const output = [
  "// This file is auto-generated by scripts/build-company-manifest.mjs. Do not edit by hand.",
  ...imports,
  "",
  "export const verifiedCompanyManifest = [",
  ...entries,
  "] as const;",
  "",
].join("\n");

fs.writeFileSync(outputFile, output, "utf8");
console.log(`Generated company manifest for ${companies.length} verified static report(s).`);
